    const listener = (_e, msg) => {
      if (msg && EVENT_TYPES.has(msg.type)) callback(msg.type, msg.payload);
    };
    ipcRenderer.on('pk:event', listener);
    return () => ipcRenderer.removeListener('pk:event', listener);
